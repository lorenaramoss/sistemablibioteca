CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(300),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash TEXT NOT NULL,
    perfil VARCHAR(20) NOT NULL DEFAULT 'bibliotecario'
        CHECK (perfil IN ('bibliotecario', 'administrador')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS livros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES categorias(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    titulo VARCHAR(200) NOT NULL,
    autor VARCHAR(150) NOT NULL,
    isbn VARCHAR(20) NOT NULL UNIQUE,
    ano_publicacao SMALLINT CHECK (ano_publicacao BETWEEN 1000 AND 9999),
    exemplares_totais INTEGER NOT NULL CHECK (exemplares_totais > 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS emprestimos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id BIGINT NOT NULL REFERENCES livros(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    leitor_nome VARCHAR(150) NOT NULL,
    data_emprestimo DATE NOT NULL DEFAULT CURRENT_DATE,
    data_prevista_devolucao DATE NOT NULL,
    data_devolucao DATE,
    status VARCHAR(12) NOT NULL DEFAULT 'ativo'
        CHECK (status IN ('ativo', 'devolvido')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_emprestimo_datas CHECK (
        data_prevista_devolucao > data_emprestimo
        AND (data_devolucao IS NULL OR data_devolucao >= data_emprestimo)
    ),
    CONSTRAINT ck_emprestimo_status_devolucao CHECK (
        (status = 'ativo' AND data_devolucao IS NULL)
        OR (status = 'devolvido' AND data_devolucao IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_livros_titulo ON livros (titulo);
CREATE INDEX IF NOT EXISTS idx_emprestimos_status_vencimento
    ON emprestimos (status, data_prevista_devolucao);
CREATE INDEX IF NOT EXISTS idx_emprestimos_livro_status
    ON emprestimos (livro_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS idx_livros_isbn_normalizado
    ON livros (regexp_replace(upper(isbn), '[^0-9X]', '', 'g'));

CREATE OR REPLACE VIEW vw_livros_disponibilidade AS
SELECT
    l.id AS livro_id,
    l.titulo,
    l.autor,
    l.isbn,
    c.nome AS categoria,
    l.exemplares_totais,
    COUNT(e.id) FILTER (WHERE e.status = 'ativo')::INTEGER AS exemplares_emprestados,
    GREATEST(
        l.exemplares_totais - COUNT(e.id) FILTER (WHERE e.status = 'ativo')::INTEGER,
        0
    ) AS exemplares_disponiveis
FROM livros l
JOIN categorias c ON c.id = l.categoria_id
LEFT JOIN emprestimos e ON e.livro_id = l.id
GROUP BY l.id, c.nome;

